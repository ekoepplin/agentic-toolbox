#!/usr/bin/env bash
# The scaffolder (issue #11): dock a host project in one command.
#
# Turns a fresh git repo on the Mac into a docked host project by generating
# the host's three-file tree — and touching nothing else in it:
#
#   compose.yaml                     the host's workbench stack: a workbench
#                                    service on the base image, the host repo
#                                    mounted as the workspace at its mirrored
#                                    Mac path, the base docked at its mirrored
#                                    Mac path, the host-specific SSH port
#                                    publish, and the standard mounts
#   .env                             the committed env file with the picked
#                                    defaults (BASE_PATH, SSH_PORT); the
#                                    compose stack interpolates both
#   .devcontainer/devcontainer.json  the thin devcontainer wrapper
#
# It picks the next free SSH port (no collision with running devcontainers —
# any port published by a running container — nor with anything else
# listening on the Mac) and ensures the base image exists, building it if
# missing (via the Makefile, the canonical builder).
#
#   usage: scripts/dock-host.sh [host-repo-path]     (default: current dir)
#            or:  make dock HOST=<path-to-host-repo>
#
# Refuses to run when any of the three files already exists — re-docking is
# an explicit act: delete the files, then re-run.
set -euo pipefail

SCRIPTS_DIR="$(cd "$(dirname "$0")" && pwd)"
BASE_DIR="$(cd "$SCRIPTS_DIR/.." && pwd)"

# Canonical base image tag — must stay the Makefile's BASE_IMAGE. The
# workbench compose stack (#9) and the scaffolder (#11) reference exactly
# this name — do not rename without updating both.
BASE_IMAGE="agentic-toolbox-base:latest"

# The docked base's mirrored Mac path: the base's own Mac path, identical in
# every host's workbench.
BASE_PATH="$BASE_DIR"

die() { echo "dock-host: $*" >&2; exit 1; }

HOST_DIR="${1:-.}"
[ -d "$HOST_DIR" ] || die "no such directory: $HOST_DIR"
git -C "$HOST_DIR" rev-parse --git-dir >/dev/null 2>&1 \
  || die "not a git repo: $HOST_DIR — the scaffolder docks fresh git repos"
# Canonicalise: a subdirectory of a repo docks the repo root.
HOST_DIR="$(git -C "$HOST_DIR" rev-parse --show-toplevel)"
HOST_NAME="$(basename "$HOST_DIR")"

command -v docker >/dev/null 2>&1 || die "docker CLI not found on PATH"
docker info >/dev/null 2>&1 || die "docker daemon not reachable — start Docker/colima first"

# ── Already docked? Refuse (never overwrite a host's own files) ────────────
existing=""
for f in compose.yaml .env .devcontainer/devcontainer.json; do
  if [ -e "$HOST_DIR/$f" ]; then
    existing="${existing}  ${f}"$'\n'
  fi
done
if [ -n "$existing" ]; then
  {
    echo "dock-host: $HOST_DIR is already docked — found:"
    printf '%s' "$existing"
    echo "dock-host: re-docking is an explicit act: delete those files (git rm if committed), then re-run."
  } >&2
  exit 1
fi

# ── Next free SSH port ──────────────────────────────────────────────────────
# The base's own workbench publishes 2224; a host takes the first free port
# at or above it. A port is taken when any running container publishes it
# (the running devcontainers / workbenches all publish their SSH port via
# compose) or when anything listens on it on the Mac. A false "taken" only
# costs a slightly higher port.
port_taken() {
  local p="$1" published
  published="$(docker ps --format '{{.Ports}}' \
    | grep -oE ':[0-9]+->' | tr -d ':-' | sort -u || true)"
  if printf '%s\n' "$published" | grep -qx "$p"; then return 0; fi
  if lsof -nP -iTCP:"$p" -sTCP:LISTEN >/dev/null 2>&1; then return 0; fi
  return 1
}

SSH_PORT=2224
while port_taken "$SSH_PORT"; do
  SSH_PORT=$((SSH_PORT + 1))
done
echo "dock-host: free SSH port: $SSH_PORT"

# ── Base image (build if missing — the Makefile is the canonical builder) ──
if docker image inspect "$BASE_IMAGE" >/dev/null 2>&1; then
  echo "dock-host: base image $BASE_IMAGE present"
else
  echo "dock-host: base image $BASE_IMAGE missing — building (make image)..."
  make -C "$BASE_DIR" image
fi

# ── The three-file tree ─────────────────────────────────────────────────────
mkdir -p "$HOST_DIR/.devcontainer"

# compose.yaml — the host's workbench stack (mirrors the base's own stack in
# the base repo; BASE_PATH and SSH_PORT interpolate from the committed .env).
cat > "$HOST_DIR/compose.yaml" <<EOF
# $HOST_NAME's workbench — docked by the agentic-toolbox base (issue #11).
# Generated by the scaffolder (scripts/dock-host.sh); re-docking refuses
# instead of overwriting, so hand edits are safe.
#
#   docker compose up -d    # start the workbench (the dock step wires every
#                           # harness adapter on each start — issue #10)
#   ssh -p $SSH_PORT node@localhost
#
# BASE_PATH and SSH_PORT come from the committed .env next to this file.

services:
  workbench:
    image: $BASE_IMAGE

    # The host repo lives at the container's working directory — its
    # mirrored Mac path.
    working_dir: $HOST_DIR

    volumes:
      # The host repo, as the workspace, at its mirrored Mac path.
      - $HOST_DIR:$HOST_DIR
      # Docked base, at its mirrored Mac path.
      - \${BASE_PATH}:\${BASE_PATH}
      # Host Claude config (settings, sessions, memory).
      - \${HOME}/.claude:/home/node/.claude
      # Staged read-only; post-create copies it to /home/node/.claude.json
      # (avoids racing with the Mac's Claude Code).
      - \${HOME}/.claude.json:/tmp/claude.json.host:ro
      # Staged SSH authorized_keys; post-create copies it into
      # /home/node/.ssh/ (the bind mount has wrong ownership for sshd).
      - \${HOME}/.ssh/container_authorized_keys:/tmp/container_authorized_keys
      # Agent logs + scratch space (survive container rebuilds).
      - \${HOME}/agent-logs:/home/node/agent-logs:cached
      - \${HOME}/agent-work:/home/node/agent-work

    ports:
      # SSH on all interfaces so Tailscale/mobile traffic reaches sshd.
      # \${SSH_PORT} is this project's published port (unique per project);
      # sshd inside the container listens on 2222.
      - "0.0.0.0:\${SSH_PORT}:2222"

    extra_hosts:
      # Local LLM endpoints sit on the Mac's loopback and are reached via
      # host.docker.internal.
      - "host.docker.internal:host-gateway"

    # Keep the container alive. sshd starts on every start (replaces the old
    # devcontainer's postStartCommand); the dock step (issue #10) wires the
    # docked base into every supported harness on every start — not just
    # first creation. A dock failure is visible in the logs and retried on
    # the next start; it never takes the workbench down.
    command: ["/bin/sh", "-c", "sudo /usr/sbin/sshd; \${BASE_PATH}/.devcontainer/scripts/dock.sh || echo 'dock: step FAILED — workbench stays up, re-run \${BASE_PATH}/.devcontainer/scripts/dock.sh manually'; exec sleep infinity"]
EOF

# .env — committed defaults the stack interpolates.
cat > "$HOST_DIR/.env" <<EOF
# Committed env file for the workbench stack — generated by the
# agentic-toolbox scaffolder (issue #11). The picked defaults that
# compose.yaml interpolates: the docked base's Mac path and this
# project's published SSH port.
BASE_PATH=$BASE_PATH
SSH_PORT=$SSH_PORT
EOF

# .devcontainer/devcontainer.json — the thin wrapper.
cat > "$HOST_DIR/.devcontainer/devcontainer.json" <<EOF
{
  // ============================================================================
  // THIN DEVCONTAINER WRAPPER — generated by the agentic-toolbox scaffolder
  // (issue #11). The workbench (base image, the docked base at its mirrored
  // Mac path, all mounts, the published SSH port, sshd startup) lives in the
  // root compose stack (compose.yaml). This file only tells VS Code which
  // service to open and what to run on first create.
  //
  //   docker compose up -d  →  Reopen in Container  →  lands in the workbench
  // ============================================================================
  "name": "$HOST_NAME",

  "dockerComposeFile": "../compose.yaml",
  "service": "workbench",
  // The host repo's mirrored Mac path — where VS Code opens and where
  // postCreateCommand runs.
  "workspaceFolder": "$HOST_DIR",

  "remoteUser": "node",

  // Runs once after container creation (not on every start). Copies the
  // staged SSH keys + claude.json. Harness wiring — the dock step — runs on
  // every start via the compose service command.
  "postCreateCommand": "bash $BASE_PATH/.devcontainer/scripts/post-create.sh"
}
EOF

# ── Validate the generated stack in the host repo ──────────────────────────
( cd "$HOST_DIR" && docker compose config -q )

echo "dock-host: docked $HOST_NAME → $HOST_DIR"
echo "dock-host:   compose.yaml                       workbench stack ($BASE_IMAGE, ssh -p $SSH_PORT)"
echo "dock-host:   .env                               BASE_PATH=$BASE_PATH, SSH_PORT=$SSH_PORT"
echo "dock-host:   .devcontainer/devcontainer.json    thin devcontainer wrapper"
echo "dock-host:   stack validated (docker compose config)"
echo "dock-host: next: cd $HOST_DIR && docker compose up -d  — or open in VS Code (Reopen in Container)"
